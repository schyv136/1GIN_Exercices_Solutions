    private void selectSpellchecker() {
        if (arrayListRadioButton.isSelected()) 
            spellchecker = new SpellcheckerArrayList();
        else if (linkedListRadioButton.isSelected()) 
            spellchecker = new SpellcheckerLinkedList();
        else if (treeSetRadioButton.isSelected()) 
            spellchecker = new SpellcheckerTreeSet();
        else 
            spellchecker = new SpellcheckerBST();
        try {
            //spellchecker.loadFromFile("DE_Wortliste_UTF8.txt");
            URL myurl = this.getClass().getResource (WORD_FILE);
            spellchecker.loadFromFile(URLDecoder.decode(myurl.getFile(), "UTF-8"));
            if ((new File(PERSONAL_DICTIONARY)).exists()) {
                spellchecker.loadFromFile(PERSONAL_DICTIONARY);
                dictionary.loadFromFile(PERSONAL_DICTIONARY);
            }
        } catch (IOException  ex) {
            System.err.println(ex);
        }
    }
    
