    private void unknownWordListValueChanged(javax.swing.event.ListSelectionEvent evt) {//GEN-FIRST:event_unknownWordListValueChanged
        int index = unknownWordList.getSelectedIndex();
        if (index > -1) {
            UnknownWord unknownWord = unknownWords.get(index);
            if (unknownWord != null) {
                textArea.setSelectionColor(Color.YELLOW);
                textArea.requestFocus();                
                textArea.setSelectionStart(unknownWord.getIndex());
                textArea.setSelectionEnd(unknownWord.getIndex() + unknownWord.getWord().length());
            }
        }
    }//GEN-LAST:event_unknownWordListValueChanged

