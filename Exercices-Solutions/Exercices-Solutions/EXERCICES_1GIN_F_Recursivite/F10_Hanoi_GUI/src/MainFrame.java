    private void calculateMovesjButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_calculateMovesjButtonActionPerformed
       try {
            hanoi = new Hanoi(Integer.valueOf(numberOfDisksTextField.getText()), 
                              Integer.valueOf(fromTextField.getText()), 
                              Integer.valueOf(toTextField.getText()));
            drawPanel1.setHanoi(hanoi);
            hanoi.calculateMoves();
            movesList.setListData(hanoi.toArray());
            numberOfMovesLabel.setText(String.valueOf(hanoi.numberOfMoves()));
            currentMoveLabel.setText(hanoi.getCurrentMove()+"/"+hanoi.numberOfMoves());
            updateView();
       }
       catch (IllegalArgumentException exc) {
           JOptionPane.showMessageDialog(rootPane, exc.getMessage());
       }
    }//GEN-LAST:event_calculateMovesjButtonActionPerformed

