    public MainFrame() {
        initComponents();
         
        showMovesTimer = new Timer (speedSlider.getValue(), new ActionListener() {

            @Override
            public void actionPerformed(ActionEvent e) {
                boolean goOn = hanoi.makeNextMove();
                if (!goOn) {
                    showMovesTimer.stop(); 
                    updateView();
                    //wait for previous timer-operations to finish 
                    //necessary if timer interval is too short for drawing operations
                    // --> mainly in turbo mode
                    try {
                        Thread.currentThread().sleep(50);
                    } catch (InterruptedException ex) {
                        Logger.getLogger(MainFrame.class.getName()).log(Level.SEVERE, null, ex);
                    }
                    repaint();
                }                
                else 
                    if (speedSlider.getValue()!=0) {
                        movesList.setSelectedIndex(hanoi.getCurrentMove());  
                        movesList.ensureIndexIsVisible(hanoi.getCurrentMove());
                        currentMoveLabel.setText(hanoi.getCurrentMove()+"/"+hanoi.numberOfMoves());
                    }
                    else { //if speed is at maximum :
                        //-> turbo mode: do not scroll list
                        currentMoveLabel.setText(hanoi.getCurrentMove()+"/"+hanoi.numberOfMoves());
                        movesList.clearSelection();                    
                    }
                drawPanel1.repaint();
            }
        });
    }

