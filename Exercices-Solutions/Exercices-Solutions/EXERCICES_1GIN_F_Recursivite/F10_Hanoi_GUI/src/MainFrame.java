    private void updateView() {
        boolean isRunning = showMovesTimer.isRunning();
        stopButton.setEnabled(isRunning); 
        calculateMovesjButton.setEnabled(!isRunning); 
        showMovesButton.setEnabled(!isRunning && hanoi.getCurrentMove()==0);
        continueButton.setEnabled (!isRunning && hanoi.getCurrentMove()!=0 && 
                                  hanoi.getCurrentMove()<hanoi.numberOfMoves()); 
        repaint();        
    }
    
